export const ERROR_CODE_DETAIL_SEPARATOR = ':'

/**
 * Splits a thrown error code into its registry code and the optional detail payload
 * appended after the separator (e.g. `NGINX_CONFIG_INVALID:<nginx -t output>`).
 */
export const splitErrorCode = (rawCode: string): { code: string; detail: string | undefined } => {
    const separatorIndex = rawCode.indexOf(ERROR_CODE_DETAIL_SEPARATOR)
    if (separatorIndex <= 0) {
        return { code: rawCode, detail: undefined }
    }

    const detail = rawCode.slice(separatorIndex + ERROR_CODE_DETAIL_SEPARATOR.length)
    return { code: rawCode.slice(0, separatorIndex), detail: detail.length > 0 ? detail : undefined }
}
